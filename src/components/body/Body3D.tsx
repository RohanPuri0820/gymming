"use client";

import { ContactShadows, OrbitControls } from "@react-three/drei";
import { Canvas, type ThreeEvent } from "@react-three/fiber";
import { useEffect, useMemo, useRef, useState, type ComponentRef } from "react";
import * as THREE from "three";
import { MUSCLES, type MuscleScores } from "@/lib/muscles";
import type { MuscleId } from "@/lib/types";
import { colorFor, type Palette } from "./palette";

export type Body3DProps = {
  scores: MuscleScores;
  palette: Palette;
  highlighted?: MuscleId[];
  onSelect?: (m: MuscleId) => void;
  view?: "front" | "back";
  autoRotate?: boolean;
};

const SKIN = new THREE.Color("#4a5468");
const SKIN_ID = 255;

type BodyMesh = { geometry: THREE.BufferGeometry; ids: Uint8Array; groove: Uint8Array; cover: Uint8Array };

// body.bin is generated by scripts/build-body.mjs ("BDY2"):
// [magic, vertexCount, indexCount] u32 · bbox f32×6 · positions u16×3 · indices u16|u32 ·
// muscle id u8 · groove u8 · coverage u8
let meshPromise: Promise<BodyMesh> | null = null;
function loadBody(): Promise<BodyMesh> {
  meshPromise ??= fetch("/body.bin")
    .then((r) => r.arrayBuffer())
    .then((buf) => {
      const [, nv, ni] = new Uint32Array(buf, 0, 3);
      const box = new Float32Array(buf, 12, 6);
      let off = 36;
      const q = new Uint16Array(buf, off, nv * 3);
      const positions = new Float32Array(nv * 3);
      for (let i = 0; i < nv * 3; i++) {
        const a = i % 3;
        positions[i] = box[a] + (q[i] / 65535) * (box[a + 3] - box[a]);
      }
      off += nv * 6;
      off += (4 - (off % 4)) % 4;
      const wide = nv > 65535;
      const index = wide ? new Uint32Array(buf, off, ni) : new Uint16Array(buf, off, ni);
      off += ni * (wide ? 4 : 2);
      const ids = new Uint8Array(buf, off, nv);
      const groove = new Uint8Array(buf, off + nv, nv);
      const cover = new Uint8Array(buf, off + 2 * nv, nv);
      const g = new THREE.BufferGeometry();
      g.setAttribute("position", new THREE.BufferAttribute(positions, 3));
      g.setAttribute("color", new THREE.BufferAttribute(new Float32Array(nv * 3), 3));
      g.setIndex(new THREE.BufferAttribute(index, 1));
      g.computeVertexNormals();
      return { geometry: g, ids, groove, cover };
    })
    .catch((e) => {
      meshPromise = null;
      throw e;
    });
  return meshPromise;
}

function Body({ scores, palette, highlighted, onSelect }: Omit<Body3DProps, "view" | "autoRotate">) {
  const [mesh, setMesh] = useState<BodyMesh | null>(null);
  const [hover, setHover] = useState<MuscleId | null>(null);
  useEffect(() => {
    loadBody().then(setMesh).catch(console.error);
  }, []);

  // Paint vertex colours whenever the data, selection or hover changes
  useEffect(() => {
    if (!mesh) return;
    const hi = new Set(highlighted ?? []);
    const colors = MUSCLES.map((m) => {
      const c = new THREE.Color(colorFor(scores[m.id], palette));
      if (hi.has(m.id)) c.lerp(new THREE.Color("#ffffff"), 0.35);
      else if (hover === m.id) c.lerp(new THREE.Color("#ffffff"), 0.18);
      return c;
    });
    const attr = mesh.geometry.getAttribute("color") as THREE.BufferAttribute;
    const arr = attr.array as Float32Array;
    for (let v = 0; v < mesh.ids.length; v++) {
      const id = mesh.ids[v];
      // Blend skin → muscle colour by coverage (soft, anti-aliased borders),
      // then darken along the groove between neighbouring regions
      const t = id === SKIN_ID ? 0 : mesh.cover[v] / 255;
      const c = id === SKIN_ID ? SKIN : colors[id];
      const k = 1 - 0.5 * (mesh.groove[v] / 255);
      arr[v * 3] = (SKIN.r + (c.r - SKIN.r) * t) * k;
      arr[v * 3 + 1] = (SKIN.g + (c.g - SKIN.g) * t) * k;
      arr[v * 3 + 2] = (SKIN.b + (c.b - SKIN.b) * t) * k;
    }
    attr.needsUpdate = true;
  }, [mesh, scores, palette, highlighted, hover]);

  useEffect(() => {
    document.body.style.cursor = hover && onSelect ? "pointer" : "";
    return () => {
      document.body.style.cursor = "";
    };
  }, [hover, onSelect]);

  const muscleAt = useMemo(
    () => (e: ThreeEvent<PointerEvent | MouseEvent>): MuscleId | null => {
      if (!mesh || !e.face) return null;
      for (const v of [e.face.a, e.face.b, e.face.c]) {
        const id = mesh.ids[v];
        if (id !== SKIN_ID) return MUSCLES[id].id;
      }
      return null;
    },
    [mesh],
  );

  if (!mesh) return null;
  return (
    <mesh
      geometry={mesh.geometry}
      onClick={(e) => {
        e.stopPropagation();
        if (e.delta > 6) return; // a drag, not a tap
        const m = muscleAt(e);
        if (m) onSelect?.(m);
      }}
      onPointerMove={(e) => {
        const m = muscleAt(e);
        setHover((h) => (h === m ? h : m));
      }}
      onPointerOut={() => setHover(null)}
    >
      <meshStandardMaterial vertexColors roughness={0.5} metalness={0.04} />
    </mesh>
  );
}

function Controls({ view, autoRotate }: { view?: "front" | "back"; autoRotate?: boolean }) {
  const ref = useRef<ComponentRef<typeof OrbitControls>>(null);
  // Idle spin until the user grabs the body
  const [spinning, setSpinning] = useState(!!autoRotate);
  useEffect(() => {
    const c = ref.current;
    if (!c) return;
    c.setAzimuthalAngle(view === "back" ? Math.PI : 0);
    c.update();
  }, [view]);
  return (
    <OrbitControls
      ref={ref}
      target={[0, 0.92, 0]}
      enablePan={false}
      minDistance={1.6}
      maxDistance={4.2}
      minPolarAngle={Math.PI * 0.18}
      maxPolarAngle={Math.PI * 0.82}
      autoRotate={spinning}
      autoRotateSpeed={0.8}
      onStart={() => setSpinning(false)}
      enableDamping
      dampingFactor={0.12}
      rotateSpeed={0.9}
    />
  );
}

export default function Body3D(props: Body3DProps) {
  return (
    <Canvas
      dpr={[1, 2]}
      camera={{ position: [0, 1.05, 3.4], fov: 32, near: 0.1, far: 20 }}
      gl={{ antialias: true }}
      style={{ touchAction: "none" }}
    >
      <ambientLight intensity={0.3} />
      <hemisphereLight args={["#dbe4ff", "#15171c", 0.75]} />
      <directionalLight position={[2, 4, 3]} intensity={1.8} />
      <directionalLight position={[-2.5, 2.5, -3]} intensity={1.0} color="#a5b4fc" />
      <directionalLight position={[0, -1, 2]} intensity={0.25} />
      <Body {...props} />
      <ContactShadows position={[0, 0.001, 0]} opacity={0.5} scale={2} blur={2.4} far={1} />
      <Controls view={props.view} autoRotate={props.autoRotate} />
    </Canvas>
  );
}
